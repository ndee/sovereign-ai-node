import { createHash } from "node:crypto";
import { chown, lstat, realpath } from "node:fs/promises";
import { dirname, join } from "node:path";

// Root-owned directory for per-command exec wrappers. OpenClaw matches exec
// allowlist entries on the executable path only, so each allowlisted command
// gets its own wrapper that fixes the full argv and takes only the declared
// placeholder values.
export const MANAGED_EXEC_WRAPPER_ROOT = "/usr/local/lib/sovereign-node/exec-wrappers";

export type ExecWrapperPlan = {
  path: string;
  executable: string;
  placeholders: string[];
  content: string;
};

export type ServiceUserIdentity = {
  uid: number;
  gids: number[];
};

type StatLike = { uid: number; gid: number; mode: number };

const PLACEHOLDER_TOKEN = /^<[^<>\s]+>$/;

const shellQuote = (value: string): string => `'${value.replaceAll("'", `'\\''`)}'`;

const slugifyCommand = (tokens: string[]): string => {
  const slug = tokens
    .filter((token) => !PLACEHOLDER_TOKEN.test(token))
    .map((token) => token.replace(/^-+/, "").replace(/[^A-Za-z0-9]+/g, "-"))
    .filter((token) => token.length > 0)
    .join("-")
    .toLowerCase()
    .slice(0, 60)
    .replace(/-+$/, "");
  return slug.length > 0 ? slug : "command";
};

/**
 * Plan the wrapper for one rendered allowlist command (`/abs/executable arg
 * <placeholder> ...`). Returns null when the command does not start with an
 * absolute executable path, which OpenClaw would not match anyway.
 */
export const planExecWrapper = (input: {
  wrapperRoot: string;
  agentId: string;
  command: string;
}): ExecWrapperPlan | null => {
  const tokens = input.command.split(" ").filter((token) => token.length > 0);
  const [executable, ...args] = tokens;
  if (executable === undefined || !executable.startsWith("/")) {
    return null;
  }
  const placeholders = args.filter((token) => PLACEHOLDER_TOKEN.test(token));
  const hash = createHash("sha256").update(input.command).digest("hex").slice(0, 8);
  const path = join(input.wrapperRoot, input.agentId, `${slugifyCommand(args)}-${hash}`);
  let position = 0;
  const execArgs = args.map((token) => {
    if (!PLACEHOLDER_TOKEN.test(token)) {
      return shellQuote(token);
    }
    position += 1;
    return `"$${String(position)}"`;
  });
  const usage = [path, ...placeholders].join(" ");
  const content = [
    "#!/bin/sh",
    "# Generated by sovereign-node: runs exactly one allowlisted command.",
    `if [ "$#" -ne ${String(placeholders.length)} ]; then`,
    `  echo ${shellQuote(`usage: ${usage}`)} >&2`,
    "  exit 64",
    "fi",
    'for arg in "$@"; do',
    '  case "$arg" in',
    `    -*) echo ${shellQuote("arguments must not start with '-'")} >&2; exit 64 ;;`,
    "  esac",
    "done",
    `exec ${[shellQuote(executable), ...execArgs].join(" ")}`,
    "",
  ].join("\n");
  return { path, executable, placeholders, content };
};

/** The invocation documented to the agent for a planned wrapper. */
export const describeExecWrapperInvocation = (plan: ExecWrapperPlan): string =>
  [plan.path, ...plan.placeholders].join(" ");

// A symlink's own mode bits mean nothing and it cannot be retargeted in place:
// replacing it needs write access to its directory, which the walk checks, and
// its target is checked through the resolved path.
const canWrite = (entry: StatLike, identity: ServiceUserIdentity): boolean =>
  (entry.mode & 0o170000) !== 0o120000 &&
  (entry.uid === identity.uid ||
    (entry.mode & 0o002) !== 0 ||
    ((entry.mode & 0o020) !== 0 && identity.gids.includes(entry.gid)));

const isChainWritable = async (
  path: string,
  identity: ServiceUserIdentity,
  statPath: (path: string) => Promise<StatLike>,
): Promise<boolean> => {
  let current = path;
  for (;;) {
    try {
      if (canWrite(await statPath(current), identity)) {
        return true;
      }
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== "ENOENT") {
        return true;
      }
    }
    const parent = dirname(current);
    if (parent === current) {
      return false;
    }
    current = parent;
  }
};

/**
 * True when the service user could change what runs at `path`: it owns, or
 * may write, the file or any directory above it, for the path itself and for
 * the path a symlink resolves to. A missing path is judged by its nearest
 * existing ancestor, because the user could create it there. Anything that
 * cannot be inspected counts as writable.
 */
export const isPathWritableByServiceUser = async (
  path: string,
  identity: ServiceUserIdentity,
  fsProbe: {
    statPath: (path: string) => Promise<StatLike>;
    resolvePath: (path: string) => Promise<string>;
  } = { statPath: lstat, resolvePath: realpath },
): Promise<boolean> => {
  if (await isChainWritable(path, identity, fsProbe.statPath)) {
    return true;
  }
  let resolved: string;
  try {
    resolved = await fsProbe.resolvePath(path);
  } catch (error) {
    return (error as NodeJS.ErrnoException).code !== "ENOENT";
  }
  return resolved !== path && (await isChainWritable(resolved, identity, fsProbe.statPath));
};

/** Parse `openclaw approvals get --json` into allowlist patterns per agent key. */
export const parseExecApprovalsSnapshot = (stdout: string): Record<string, string[]> | null => {
  const start = stdout.indexOf("{");
  const end = stdout.lastIndexOf("}");
  if (start < 0 || end < start) {
    return null;
  }
  let parsed: unknown;
  try {
    parsed = JSON.parse(stdout.slice(start, end + 1));
  } catch {
    return null;
  }
  const isRecord = (value: unknown): value is Record<string, unknown> =>
    value !== null && typeof value === "object" && !Array.isArray(value);
  const snapshot = parsed as Record<string, unknown>;
  const file = isRecord(snapshot.file) ? snapshot.file : {};
  const agents = isRecord(file.agents) ? file.agents : {};
  const result: Record<string, string[]> = {};
  for (const [agentKey, agent] of Object.entries(agents)) {
    const allowlist = isRecord(agent) && Array.isArray(agent.allowlist) ? agent.allowlist : [];
    const patterns = allowlist
      .map((entry) =>
        typeof entry === "string" ? entry : isRecord(entry) ? entry.pattern : undefined,
      )
      .filter((pattern): pattern is string => typeof pattern === "string")
      .map((pattern) => pattern.trim())
      .filter((pattern) => pattern.length > 0);
    if (patterns.length > 0) {
      result[agentKey] = Array.from(new Set(patterns));
    }
  }
  return result;
};

/**
 * Changes that turn the current approvals into exactly the expected set. Any
 * entry node did not ask for is removed, including wildcard-agent ("*")
 * entries, which would apply to every agent.
 */
export const planExecApprovalsReconciliation = (
  current: Record<string, string[]>,
  expected: Record<string, string[]>,
): {
  remove: Array<{ agent: string; pattern: string }>;
  add: Array<{ agent: string; pattern: string }>;
} => {
  const remove = Object.entries(current).flatMap(([agent, patterns]) =>
    patterns
      .filter((pattern) => !(expected[agent] ?? []).includes(pattern))
      .map((pattern) => ({ agent, pattern })),
  );
  const add = Object.entries(expected).flatMap(([agent, patterns]) =>
    Array.from(new Set(patterns))
      .filter((pattern) => !(current[agent] ?? []).includes(pattern))
      .map((pattern) => ({ agent, pattern })),
  );
  return { remove, add };
};

export type ExecPinningEnvironment = {
  wrapperRoot: string;
  runningAsRoot: () => boolean;
  resolveServiceUser: (user: string) => Promise<ServiceUserIdentity | null>;
  isPathWritable: (path: string, identity: ServiceUserIdentity) => Promise<boolean>;
  chownToRoot: (path: string) => Promise<void>;
};

/** `run` executes `id <args>` and returns its trimmed stdout, or null on failure. */
export const resolveServiceUserIdentity = async (
  user: string,
  run: (args: string[]) => Promise<string | null>,
): Promise<ServiceUserIdentity | null> => {
  const uidText = await run(["-u", user]);
  const gidsText = await run(["-G", user]);
  if (uidText === null || gidsText === null || !/^\d+$/.test(uidText)) {
    return null;
  }
  const gids = gidsText
    .split(/\s+/)
    .filter((entry) => /^\d+$/.test(entry))
    .map(Number);
  return { uid: Number(uidText), gids };
};

export const createDefaultExecPinningEnvironment = (
  runId: (args: string[]) => Promise<string | null>,
): ExecPinningEnvironment => ({
  wrapperRoot: MANAGED_EXEC_WRAPPER_ROOT,
  runningAsRoot: () => typeof process.getuid === "function" && process.getuid() === 0,
  resolveServiceUser: async (user) => await resolveServiceUserIdentity(user, runId),
  isPathWritable: async (path, identity) => await isPathWritableByServiceUser(path, identity),
  chownToRoot: (path) => chown(path, 0, 0),
});
